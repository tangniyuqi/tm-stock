// Package render 是 AI 报告的渲染器与输出结构校验器。
//
// 设计依据：docs/specs/ai-analysis/design.md 第 3.3 节。核心约束：
//
//   - 用户可见节点只有三类：模板句（由封闭谓词库按模板渲染）、引文块（逐字引文）、数据行（客观字段）；
//     自由文本节点数为 0（AC-G1）。模型的输出永远不会直接变成用户看到的文字。
//   - 报告结构里没有 rating、score、rank、target、leader、relevance、tier、direction、confidence 这类字段
//     （AC-G5，由字段名守卫测试在 CI 里扫描）；个股数据行只含名称、代码、归属环节、依据、涨跌幅（AC-G6）。
//   - 每个节点带来源性质 provenance（资料库人工审核内容 / AI 抽取的引文 / 代码计算的数据），
//     只有含 AI 抽取内容的部分才带"AI 生成"标识，资料库内容与代码计算内容不冒充 AI（AC-G8）。
//   - "AI 生成"标识、模型名称、备案号由代码注入（Disclosure），不由模型输出。
//
// Validate 是整份报告落库、返回给用户之前的最后一道结构闸门：模板句会按谓词与参数重新渲染并逐字比对，
// 任何被改动过的文字、白名单外的节点、越界的字段取值都会被拒绝。
